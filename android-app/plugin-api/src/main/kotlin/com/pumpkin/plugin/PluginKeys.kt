package com.pumpkin.plugin

/**
 * 覆盖板的键清单。
 *
 * **这里是插件与 App 之间唯一的契约面。**
 *
 * 插件能影响 App 的哪些地方，取决于 App 在哪里读了这些键 ——
 * 所以这份清单必须和 App 侧的读取点一一对应（搜 `PluginKeys.` 就能找到全部）。
 * 加一个新键时，请同时：
 *   1. 在这里加常量，并写清楚「值长什么样、非法值怎么办」；
 *   2. 在 App 读它的地方做兜底（插件写进来的可能是任何字符串）。
 *
 * 键名用 `<区域>.<名字>` 的点分形式：撞车一眼能看出来，也方便 App 按前缀批量处理。
 */
object PluginKeys {

    /**
     * 运行页控制台的**字号倍率**，如 `"1.5"`。
     *
     * - 基准是 App 内置的 10.5sp，所以 `1` 就是内置大小；
     * - 合法范围 0.5~3，App 侧解析失败或越界时**夹回 1**（不是夹到边界），
     *   这样插件写错值只会「看起来没生效」，不会把日志区搞成一行一个字。
     */
    const val CONSOLE_FONT_SCALE = "console.fontScale"
}
